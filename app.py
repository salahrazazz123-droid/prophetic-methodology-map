DB_PATH = "bukhari.db"
JSON_PATH = "bukhari.json"   # ضع هنا ملف البخاري عند توفره

@st.cache_resource
def get_bukhari_db():
    conn = sqlite3.connect(DB_PATH, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    c = conn.cursor()
    c.execute("""
        CREATE TABLE IF NOT EXISTS hadiths (
            id INTEGER PRIMARY KEY,
            number INTEGER,
            text TEXT NOT NULL,
            book TEXT,
            narrator TEXT
        )
    """)
    conn.commit()

    # التحميل التلقائي من JSON إذا وُجد وكانت القاعدة فارغة
    c.execute("SELECT COUNT(*) FROM hadiths")
    if c.fetchone()[0] == 0 and os.path.exists(JSON_PATH):
        with open(JSON_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
        for item in data:
            c.execute(
                "INSERT OR IGNORE INTO hadiths (id, number, text, book, narrator) VALUES (?,?,?,?,?)",
                (item.get("id"), item.get("number"), item.get("text"),
                 item.get("book", ""), item.get("narrator", ""))
            )
        conn.commit()
    return conn

def bukhari_stats():
    conn = get_bukhari_db()
    c = conn.cursor()
    c.execute("SELECT COUNT(*) FROM hadiths")
    return c.fetchone()[0]

def search_bukhari(query, limit=10):
    """بحث نصي في صحيح البخاري"""
    conn = get_bukhari_db()
    c = conn.cursor()
    q = f"%{query}%"
    c.execute("""
        SELECT * FROM hadiths
        WHERE text LIKE ? OR book LIKE ? OR narrator LIKE ?
        ORDER BY number LIMIT ?
    """, (q, q, q, limit))
    return c.fetchall()

def get_hadith_by_number(number):
    conn = get_bukhari_db()
    c = conn.cursor()
    c.execute("SELECT * FROM hadiths WHERE number = ?", (number,))
    return c.fetchone()

