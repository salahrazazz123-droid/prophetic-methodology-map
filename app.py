def card_id(card):
    """معرّف فريد ثابت للبطاقة مبني على المصدر والنص."""
    raw = f"{card.get('source','')}|{card.get('text','')[:40]}|{card.get('dim','')}"
    return "H-" + str(abs(hash(raw)) % (10 ** 10)).zfill(10)


