def analyze_hadith_ai(hadith_text, api_key):
    """تحليل الحديث عبر Gemini."""
    models_to_try = ["gemini-flash-latest", "gemini-flash-lite-latest", "gemini-2.5-flash"]
    last_error = None
    for model_name in models_to_try:
        try:
            genai.configure(api_key=api_key)
            model = genai.GenerativeModel(model_name=model_name, system_instruction=SYSTEM_PROMPT)
            response = model.generate_content(hadith_text)
            return response.text, None
        except Exception as e:
            last_error = str(e)
            if "429" in last_error or "quota" in last_error.lower():
                continue
            return None, last_error
    return None, "⚠️ انتهت الحصص المجانية. جرّب وضع العرض السريع أو حاول لاحقًا."


